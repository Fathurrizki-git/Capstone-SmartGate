-- ============================================================
-- SKEMA DATABASE LOKAL POSTGRESQL (MINI PC GERBANG KELUAR)
-- Dijalankan otomatis oleh local_db.py saat sistem pertama kali terhubung.
-- Struktur mengikuti tabel Supabase (supabase/schema.sql) + kolom sinkronisasi.
-- ============================================================

-- 1. AKUN PETUGAS (salinan dari Supabase, password disimpan sebagai hash PBKDF2)
CREATE TABLE IF NOT EXISTS users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  remote_id BIGINT UNIQUE,
  name VARCHAR(100) NOT NULL,
  email VARCHAR(100) UNIQUE NOT NULL,
  password_hash VARCHAR(255) NOT NULL,
  role VARCHAR(50) NOT NULL,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 2. SESI LOGIN DASHBOARD LOKAL (tetap berlaku walau program di-restart)
CREATE TABLE IF NOT EXISTS sessions (
  token VARCHAR(64) PRIMARY KEY,
  user_email VARCHAR(100) NOT NULL REFERENCES users (email) ON DELETE CASCADE,
  expires_at TIMESTAMPTZ NOT NULL
);

-- 3. KENDARAAN CIVITAS TERDAFTAR (sinkron dua arah dengan Supabase)
CREATE TABLE IF NOT EXISTS registered_vehicles (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  remote_id BIGINT UNIQUE,                     -- id baris di Supabase (NULL = belum pernah terkirim)
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  plate VARCHAR(20) NOT NULL,
  plate_norm VARCHAR(20) GENERATED ALWAYS AS (UPPER(REGEXP_REPLACE(plate, '[^A-Za-z0-9]', '', 'g'))) STORED UNIQUE,
  owner VARCHAR(100) NOT NULL,
  category VARCHAR(50) NOT NULL CHECK (category IN ('STUDENT', 'LECTURER', 'ACADEMIC COMMUNITY', 'OTHERS')),
  nim_nip VARCHAR(50),
  rfid_uid VARCHAR(50) UNIQUE,
  dirty BOOLEAN NOT NULL DEFAULT FALSE,        -- perubahan lokal yang belum dikirim ke Supabase
  deleted BOOLEAN NOT NULL DEFAULT FALSE       -- dihapus lokal, menunggu dihapus juga di Supabase
);

-- 4. RIWAYAT KENDARAAN KELUAR (ditulis lokal dulu, lalu dikirim ke Supabase)
CREATE TABLE IF NOT EXISTS vehicle_logs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  client_uuid UUID NOT NULL UNIQUE,            -- id unik agar log tidak terkirim dobel ke Supabase
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  plate VARCHAR(20) NOT NULL,
  name VARCHAR(100) DEFAULT 'Guest',
  category VARCHAR(50) DEFAULT 'GUEST',
  nim_nip VARCHAR(50) DEFAULT '-',
  status VARCHAR(50) NOT NULL,
  method VARCHAR(20) DEFAULT 'ALPR',
  direction VARCHAR(10) DEFAULT 'OUT',
  confidence NUMERIC(5, 2) NOT NULL,
  region VARCHAR(20) DEFAULT 'id',
  synced BOOLEAN NOT NULL DEFAULT FALSE        -- FALSE = antre dikirim saat internet tersedia
);

-- Database lama: perbarui daftar kategori yang diizinkan (tambah OTHERS). Aman dijalankan ulang.
ALTER TABLE registered_vehicles DROP CONSTRAINT IF EXISTS registered_vehicles_category_check;
ALTER TABLE registered_vehicles ADD CONSTRAINT registered_vehicles_category_check
  CHECK (category IN ('STUDENT', 'LECTURER', 'ACADEMIC COMMUNITY', 'OTHERS'));

CREATE INDEX IF NOT EXISTS idx_vehicle_logs_unsynced ON vehicle_logs (id) WHERE NOT synced;
CREATE INDEX IF NOT EXISTS idx_vehicle_logs_created ON vehicle_logs (created_at DESC);

-- 5. SECURITY NOTIFICATION (dokumentasi isi notifikasi), dikirim ke Supabase security_alerts.
--    Diisi otomatis dari vehicle_logs oleh local_db.py (SECURITY_ALERTS_FROM_LOGS_SQL).
DROP TABLE IF EXISTS alert_states;

CREATE TABLE IF NOT EXISTS security_alerts (
  log_uuid UUID PRIMARY KEY,                   -- = vehicle_logs.client_uuid (log asal notifikasi)
  created_at TIMESTAMPTZ NOT NULL,             -- waktu kejadian (sama dengan log)
  alert_type VARCHAR(20) NOT NULL CHECK (alert_type IN ('UNREGISTERED', 'RFID_MISMATCH', 'MANUAL_OPEN', 'OCR_LOW')),
  severity VARCHAR(10) NOT NULL,               -- 'danger' / 'warning' / 'info'
  title VARCHAR(150) NOT NULL,
  description TEXT,
  plate VARCHAR(20),
  rfid_uid VARCHAR(50),                        -- kartu yang di-tap (kendaraan belum terdaftar)
  confidence NUMERIC(5, 2),
  synced BOOLEAN NOT NULL DEFAULT FALSE        -- FALSE = belum terkirim ke Supabase
);

-- Database yang sempat memakai versi dengan kolom status: buang kolom yang tidak dipakai
DROP INDEX IF EXISTS idx_security_alerts_dirty;
ALTER TABLE security_alerts
  DROP COLUMN IF EXISTS is_read,
  DROP COLUMN IF EXISTS dismissed,
  DROP COLUMN IF EXISTS dirty,
  DROP COLUMN IF EXISTS updated_at;

CREATE INDEX IF NOT EXISTS idx_security_alerts_unsynced ON security_alerts (created_at) WHERE NOT synced;
