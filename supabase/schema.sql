-- 1. TABEL USERS (Daftar Akun Pengguna / Admin / Satpam)
CREATE TABLE IF NOT EXISTS public.users (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at TIMESTAMPTZ DEFAULT NOW(),
  name VARCHAR(100) NOT NULL,
  email VARCHAR(100) UNIQUE NOT NULL,
  password VARCHAR(255) NOT NULL,
  role VARCHAR(50) NOT NULL CHECK (role IN ('ADMIN', 'SATPAM'))
);

ALTER TABLE public.users ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Allow public read users" ON public.users FOR SELECT USING (true);
CREATE POLICY "Allow public insert users" ON public.users FOR INSERT WITH CHECK (true);
CREATE POLICY "Allow public delete users" ON public.users FOR DELETE USING (true);

-- 2. TABEL REGISTERED VEHICLES (Daftar Kendaraan Civitas Terdaftar)
CREATE TABLE IF NOT EXISTS public.registered_vehicles (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at TIMESTAMPTZ DEFAULT NOW(),
  plate VARCHAR(20) UNIQUE NOT NULL,
  owner VARCHAR(100) NOT NULL,
  category VARCHAR(50) NOT NULL CHECK (category IN ('STUDENT', 'LECTURER', 'ACADEMIC COMMUNITY', 'OTHERS')),
  nim_nip VARCHAR(50),
  rfid_uid VARCHAR(50) UNIQUE,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW() -- dipakai sinkronisasi database lokal Mini PC
);

CREATE OR REPLACE FUNCTION public.set_updated_at() RETURNS trigger AS $$
BEGIN
  NEW.updated_at = NOW();
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_registered_vehicles_updated_at ON public.registered_vehicles;
CREATE TRIGGER trg_registered_vehicles_updated_at
  BEFORE UPDATE ON public.registered_vehicles
  FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();

ALTER TABLE public.registered_vehicles ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Allow public read registered_vehicles" ON public.registered_vehicles FOR SELECT USING (true);
CREATE POLICY "Allow public insert registered_vehicles" ON public.registered_vehicles FOR INSERT WITH CHECK (true);
CREATE POLICY "Allow public update registered_vehicles" ON public.registered_vehicles FOR UPDATE USING (true);
CREATE POLICY "Allow public delete registered_vehicles" ON public.registered_vehicles FOR DELETE USING (true);

-- 3. TABEL VEHICLE LOGS (Riwayat Arus Kendaraan Masuk/Keluar)
CREATE TABLE IF NOT EXISTS public.vehicle_logs (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at TIMESTAMPTZ DEFAULT NOW(),
  plate VARCHAR(20) NOT NULL,
  name VARCHAR(100) DEFAULT 'Guest',
  category VARCHAR(50) DEFAULT 'GUEST',
  nim_nip VARCHAR(50) DEFAULT '-',
  status VARCHAR(50) NOT NULL,
  method VARCHAR(20) DEFAULT 'ALPR', -- 'ALPR+RFID', 'MANUAL', 'WEB_MANUAL', 'DUAL_QUICK_REG', 'QUICK_REG_WEB'
  direction VARCHAR(10) DEFAULT 'OUT',
  confidence NUMERIC(5, 2) NOT NULL,
  region VARCHAR(20) DEFAULT 'id',
  client_uuid UUID UNIQUE -- id log dari Mini PC, mencegah log terkirim dobel
);

ALTER TABLE public.vehicle_logs ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Allow public read vehicle_logs" ON public.vehicle_logs FOR SELECT USING (true);
CREATE POLICY "Allow public insert vehicle_logs" ON public.vehicle_logs FOR INSERT WITH CHECK (true);
CREATE POLICY "Allow public delete vehicle_logs" ON public.vehicle_logs FOR DELETE USING (true);

ALTER PUBLICATION supabase_realtime ADD TABLE public.vehicle_logs;

-- 4. TABEL GATE COMMANDS (Perintah Buka Palang Manual via Web Dashboard)
CREATE TABLE IF NOT EXISTS public.gate_commands (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at TIMESTAMPTZ DEFAULT NOW(),
  command VARCHAR(50) NOT NULL DEFAULT 'OPEN_GATE',
  status VARCHAR(20) NOT NULL DEFAULT 'PENDING', -- 'PENDING', 'EXECUTED', 'EXPIRED'
  operator_name VARCHAR(100) DEFAULT 'Petugas',
  reason VARCHAR(255) DEFAULT 'Buka Gerbang Manual via Web Dashboard',
  executed_at TIMESTAMPTZ
);

ALTER TABLE public.gate_commands ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Allow public read gate_commands" ON public.gate_commands FOR SELECT USING (true);
CREATE POLICY "Allow public insert gate_commands" ON public.gate_commands FOR INSERT WITH CHECK (true);
CREATE POLICY "Allow public update gate_commands" ON public.gate_commands FOR UPDATE USING (true);
CREATE POLICY "Allow public delete gate_commands" ON public.gate_commands FOR DELETE USING (true);

ALTER PUBLICATION supabase_realtime ADD TABLE public.gate_commands;

-- 4b. TABEL SECURITY ALERTS (dokumentasi isi Security Notification)
--     Dicatat Mini PC dari vehicle_logs lalu dikirim oleh sinkronisasi (hanya tambah, tidak diubah).
--     Status dibaca/dihapus notifikasi disimpan di browser masing-masing petugas, bukan di sini.
DROP TABLE IF EXISTS public.alert_states;

CREATE TABLE IF NOT EXISTS public.security_alerts (
  log_uuid UUID PRIMARY KEY,                   -- = vehicle_logs.client_uuid (log asal notifikasi)
  created_at TIMESTAMPTZ NOT NULL,             -- waktu kejadian (sama dengan log)
  alert_type VARCHAR(20) NOT NULL CHECK (alert_type IN ('UNREGISTERED', 'RFID_MISMATCH', 'MANUAL_OPEN', 'OCR_LOW')),
  severity VARCHAR(10) NOT NULL,               -- 'danger' / 'warning' / 'info'
  title VARCHAR(150) NOT NULL,
  description TEXT,
  plate VARCHAR(20),
  rfid_uid VARCHAR(50),                        -- kartu yang di-tap (kendaraan belum terdaftar)
  confidence NUMERIC(5, 2)
);

-- Project yang sempat memakai versi dengan kolom status: buang kolom & trigger yang tidak dipakai
DROP TRIGGER IF EXISTS trg_security_alerts_updated_at ON public.security_alerts;
DROP INDEX IF EXISTS public.idx_security_alerts_updated;
ALTER TABLE public.security_alerts
  DROP COLUMN IF EXISTS is_read,
  DROP COLUMN IF EXISTS dismissed,
  DROP COLUMN IF EXISTS updated_at;

CREATE INDEX IF NOT EXISTS idx_security_alerts_created ON public.security_alerts (created_at DESC);

ALTER TABLE public.security_alerts ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Allow public read security_alerts" ON public.security_alerts;
DROP POLICY IF EXISTS "Allow public insert security_alerts" ON public.security_alerts;
DROP POLICY IF EXISTS "Allow public update security_alerts" ON public.security_alerts;
CREATE POLICY "Allow public read security_alerts" ON public.security_alerts FOR SELECT USING (true);
CREATE POLICY "Allow public insert security_alerts" ON public.security_alerts FOR INSERT WITH CHECK (true);

